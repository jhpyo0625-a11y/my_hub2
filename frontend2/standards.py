_STRIP = " \t\n\r-_·・.()（）"


def norm_key(s) -> str:
    """표기를 비교용 키로 정규화합니다. 공백·하이픈·괄호를 지우고 소문자로."""
    out = []
    for ch in str(s or "").lower():
        if ch not in _STRIP:
            out.append(ch)
    return "".join(out)


