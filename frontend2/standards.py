#   rank 는 성분 카드를 정렬하는 순서입니다. 숫자가 클수록 앞에 옵니다.
# =============================================================================
LEVEL_RANK = {"over": 5, "near": 4, "low": 3, "none": 2, "unknown": 1, "met": 0}

# '상한의 몇 %부터 상한 근접으로 볼지'. 0.7 = 70%.
NEAR_RATIO = 0.7


def level_of(supp: float, total: float, std) -> str:
    """이 성분이 지금 어떤 상태인지 한 단어로."""
    if not std or (std.get("rda") is None and std.get("ul") is None):
        return "unknown"
    if not (total > 0):
        return "none"
    # 상한을 무엇과 비교할지 — 마그네슘·엽산처럼 보충제 기준 상한이 있는
    # 성분은 식사분을 빼고 영양제 섭취량만으로 비교합니다.
    ul_amount = supp if std.get("ul_basis") == "supp" else total
    ul = std.get("ul")
    rda = std.get("rda")
    if ul is not None and ul_amount > ul:
        return "over"
    if ul is not None and ul_amount >= ul * NEAR_RATIO:
        return "near"
    if rda is not None and total >= rda:
        return "met"
    return "low"


